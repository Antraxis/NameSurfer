package com.shpp.p2p.cs.pkrmarenko.namesurfer;


import com.shpp.cs.a.simple.SimpleProgram;

import javax.swing.*;
import java.awt.*;
import java.awt.event.ActionEvent;
import java.awt.event.KeyEvent;
import java.awt.event.KeyListener;

public class NameSurfer extends SimpleProgram implements NameSurferConstants {

    // UI components and interactive elements
    JButton buttonName = new JButton(BUTTON_GRAPH_TEXT);
    JButton buttonClear = new JButton(BUTTON_CLEAR_TEXT);
    JButton buttonDeleteGrid = new JButton(BUTTON_DELETE_GRID_TEXT);
    JLabel labelName = new JLabel(LABEL_NAME_TEXT);
    JTextField foundName = new JTextField(TEXT_FIELD_COLUMNS);


    // Graph display and database instances
    NameSurferGraph objGraph = new NameSurferGraph();
    NameSurferEntry objEntry;
    NameSurferDataBase objData = new NameSurferDataBase(NAMES_DATA_FILE);

    /**
     * This method has the responsibility for reading in the database
     * and initializing the interactors at the top of the window.
     */
    public void init() {
        add(labelName, BorderLayout.NORTH);
        add(foundName, BorderLayout.NORTH);
        add(buttonName, BorderLayout.NORTH);
        add(buttonClear, BorderLayout.NORTH);
        add(buttonDeleteGrid, BorderLayout.NORTH);
        add(objGraph);

        foundName.setActionCommand(buttonClear.getText());
        addActionListeners();

        // Key listener to handle 'Enter' press inside the text field for quick submission
        foundName.addKeyListener(new KeyListener() {
            @Override
            public void keyTyped(KeyEvent keyEvent) {
            }

            @Override
            public void keyPressed(KeyEvent keyEvent) {
                if (keyEvent.getKeyCode() == KeyEvent.VK_ENTER) {
                    actionAfterEnter();
                }
            }

            @Override
            public void keyReleased(KeyEvent keyEvent) {
            }
        });
    }

    /**
     * This class (method) is responsible for detecting when the buttons are
     * clicked, so you will have to define a method to respond to
     * button actions.
     *
     * @param e the action event generated by user interaction
     */
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == buttonName) {
            actionAfterEnter();
        }
        if (e.getSource() == buttonClear) {
            objGraph.clear();
        }
        if (e.getSource() == buttonDeleteGrid) {
            objGraph.deleteGrid();
        }
    }

    /**
     * Searches for the entered name in the database and adds it to the graph
     * if found, or displays an error dialog box otherwise.
     */
    private void actionAfterEnter() {
        objEntry = objData.findEntry(foundName.getText());
        if (objEntry != null) {
            objGraph.addEntry(objEntry);
        } else {
            JOptionPane.showMessageDialog(null, ERROR_NAME_NOT_FOUND);
        }
    }
}